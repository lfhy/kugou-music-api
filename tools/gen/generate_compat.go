package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"strings"

	"github.com/lfhy/kugou-music-api/core/parser"
)

type compatShardSpec struct {
	filename string
	funcName string
	startID  string
	endID    string
}

// Generated compat rules are sharded so they stay diff-friendly after regeneration.
func writeCompatGenerated(models []apiModel) error {
	core, groups, err := buildCompatOutputs(models)
	if err != nil {
		return err
	}
	if err := writeGeneratedCompatFile("sdk/generated_compat_core.go", core); err != nil {
		return err
	}
	for path, src := range groups {
		if err := writeGeneratedCompatFile(path, src); err != nil {
			return err
		}
	}
	_ = os.Remove("sdk/generated_compat.go")
	return nil
}

func buildCompatOutputs(models []apiModel) ([]byte, map[string][]byte, error) {
	shards := generatedCompatShards()
	order := make(map[string]int, len(models))
	for i, m := range models {
		order[m.Identifier] = i
	}
	buffers := make(map[string]*strings.Builder, len(shards))
	for _, shard := range shards {
		buffers[shard.filename] = &strings.Builder{}
	}
	for _, m := range models {
		snippet, ok := renderCompatCase(m)
		if !ok {
			continue
		}
		shard := compatShardForIdentifier(m.Identifier, shards, order)
		buffers[shard.filename].WriteString(snippet)
	}

	core := buildCompatCore(shards)
	groups := make(map[string][]byte, len(shards))
	for _, shard := range shards {
		var b strings.Builder
		b.WriteString("// Code generated by tools/gen; DO NOT EDIT.\npackage sdk\n\n")
		if strings.Contains(buffers[shard.filename].String(), "fmt.") {
			b.WriteString("import \"fmt\"\n\n")
		}
		b.WriteString(fmt.Sprintf("func %s(identifier string, in map[string]any, cookie map[string]string) (map[string]any, bool) {\n\tswitch identifier {\n", shard.funcName))
		b.WriteString(buffers[shard.filename].String())
		b.WriteString("\tdefault:\n\t\treturn nil, false\n\t}\n}\n")
		groups[shard.filename] = []byte(b.String())
	}
	return core, groups, nil
}

func generatedCompatShards() []compatShardSpec {
	return []compatShardSpec{
		{"sdk/generated_compat_group_a.go", "buildCompatParamsGroupA", "ai_recommend", "comment_music_hotword"},
		{"sdk/generated_compat_group_b.go", "buildCompatParamsGroupB", "comment_playlist", "pc_diantai"},
		{"sdk/generated_compat_group_c.go", "buildCompatParamsGroupC", "personal_fm", "search_lyric"},
		{"sdk/generated_compat_group_d.go", "buildCompatParamsGroupD", "search_mixed", "top_song"},
		{"sdk/generated_compat_group_e.go", "buildCompatParamsGroupE", "user_cloud", "yueku_banner"},
	}
}

func compatShardForIdentifier(identifier string, shards []compatShardSpec, order map[string]int) compatShardSpec {
	pos := order[identifier]
	for _, shard := range shards {
		if pos >= order[shard.startID] && pos <= order[shard.endID] {
			return shard
		}
	}
	panic("missing compat shard for " + identifier)
}

func renderCompatCase(m apiModel) (string, bool) {
	rules := m.Compat.DataMapRules
	if len(rules) == 0 {
		rules = m.Compat.ParamsMapRules
	}
	if len(rules) == 0 {
		return "", false
	}
	var b strings.Builder
	b.WriteString(fmt.Sprintf("\tcase %q:\n", m.Identifier))
	b.WriteString("\t\tout := map[string]any{}\n")
	for _, r := range rules {
		expr := toGoCompatExpr(r.Expr, "in", "cookie")
		if expr == "" {
			continue
		}
		b.WriteString(fmt.Sprintf("\t\tout[%q] = %s\n", r.Field, expr))
	}
	b.WriteString("\t\tfor k, v := range in { if _, ok := out[k]; !ok { out[k] = v } }\n")
	b.WriteString("\t\treturn out, true\n")
	return b.String(), true
}

func buildCompatCore(shards []compatShardSpec) []byte {
	var b bytes.Buffer
	b.WriteString("// Code generated by tools/gen; DO NOT EDIT.\npackage sdk\n\n")
	b.WriteString("import (\n\t\"fmt\"\n\t\"strconv\"\n)\n\n")
	b.WriteString("func buildCompatParams(identifier string, in map[string]any, cookie map[string]string) (map[string]any, bool) {\n")
	for _, shard := range shards {
		b.WriteString(fmt.Sprintf("\tif out, ok := %s(identifier, in, cookie); ok {\n\t\treturn out, true\n\t}\n", shard.funcName))
	}
	b.WriteString("\treturn in, false\n}\n\n")
	b.WriteString("func applyCompatCookie(identifier string, cookie map[string]string) map[string]string {\n\tout := map[string]string{}\n\tfor k, v := range cookie { out[k] = v }\n\tswitch identifier {\n\tcase \"captcha_sent\":\n\t\tif v := cookie[\"KUGOU_API_MID\"]; v != \"\" { out[\"mid\"] = v }\n\t}\n\treturn out\n}\n\n")
	b.WriteString("func compatFirstAny(v ...any) any {\n\tfor _, x := range v {\n\t\tswitch vv := x.(type) {\n\t\tcase nil:\n\t\t\tcontinue\n\t\tcase string:\n\t\t\tif vv != \"\" { return vv }\n\t\tdefault:\n\t\t\treturn x\n\t\t}\n\t}\n\treturn nil\n}\n\n")
	b.WriteString("func compatFirstAnyString(v any, def string) string {\n\tif v == nil { return def }\n\ts := fmt.Sprintf(\"%v\", v)\n\tif s == \"\" || s == \"<nil>\" { return def }\n\treturn s\n}\n\n")
	b.WriteString("func compatFirstAnyInt(v any, def int) int {\n\tif v == nil { return def }\n\ts := fmt.Sprintf(\"%v\", v)\n\tif s == \"\" || s == \"<nil>\" { return def }\n\tn, err := strconv.Atoi(s)\n\tif err != nil || n == 0 { return def }\n\treturn n\n}\n\n")
	b.WriteString("func compatDefaultLiteral(kind string, s string, i int, bval bool) any {\n\tswitch kind {\n\tcase \"string\":\n\t\treturn s\n\tcase \"int\":\n\t\treturn i\n\tcase \"bool\":\n\t\treturn bval\n\tdefault:\n\t\treturn nil\n\t}\n}\n")
	return b.Bytes()
}

func writeGeneratedCompatFile(path string, src []byte) error {
	formatted, err := format.Source(src)
	if err != nil {
		_ = os.WriteFile(path+".unformatted", src, 0o644)
		return err
	}
	return os.WriteFile(path, formatted, 0o644)
}

func toGoCompatExpr(expr parser.CompatExpr, inVar, cookieVar string) string {
	switch expr.Kind {
	case parser.ExprLiteralString:
		return fmt.Sprintf("%q", expr.DefaultStr)
	case parser.ExprLiteralInt:
		return fmt.Sprintf("%d", expr.DefaultInt)
	case parser.ExprLiteralBool:
		if expr.DefaultBool {
			return "true"
		}
		return "false"
	case parser.ExprParam:
		return fmt.Sprintf("%s[%q]", inVar, expr.ParamKey)
	case parser.ExprCookie:
		return fmt.Sprintf("%s[%q]", cookieVar, expr.CookieKey)
	case parser.ExprParamOrString:
		return fmt.Sprintf("compatFirstAnyString(%s[%q], %q)", inVar, expr.ParamKey, expr.DefaultStr)
	case parser.ExprParamOrInt:
		return fmt.Sprintf("compatFirstAnyInt(%s[%q], %d)", inVar, expr.ParamKey, expr.DefaultInt)
	case parser.ExprParamOrCookie:
		return fmt.Sprintf("compatFirstAny(%s[%q], %s[%q], compatDefaultLiteral(%q, %q, %d, %t))", inVar, expr.ParamKey, cookieVar, expr.CookieKey, expr.DefaultType, expr.DefaultStr, expr.DefaultInt, expr.DefaultBool)
	case parser.ExprTemplateParam:
		return fmt.Sprintf("fmt.Sprintf(\"%%v\", %s[%q])", inVar, expr.ParamKey)
	case parser.ExprNumberOrInt:
		return fmt.Sprintf("compatFirstAnyInt(%s[%q], %d)", inVar, expr.ParamKey, expr.DefaultInt)
	default:
		return ""
	}
}
