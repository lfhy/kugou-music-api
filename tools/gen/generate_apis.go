type apiShardSpec struct {
	filename string
	comment  string
	startID  string
	endID    string
}

// Generated API output is sharded so the checked-in SDK files stay reviewable.
func writeGeneratedGo(models []apiModel) error {
	if err := writeFormattedFile("sdk/generated_api_core.go", buildGeneratedAPICore(models)); err != nil {
		return err
	}
	if err := writeFormattedFile("sdk/generated_api_catalog.go", buildGeneratedAPICatalog(models)); err != nil {
		return err
	}
	if err := writeFormattedFile("sdk/generated_api_specs.go", buildGeneratedAPISpecs(models)); err != nil {
		return err
	}

	order := make(map[string]int, len(models))
	for i, m := range models {
		order[m.Identifier] = i
	}
	shards := generatedAPIShards()
	buffers := make(map[string]*strings.Builder, len(shards))
	needsContext := make(map[string]bool, len(shards))
	for _, shard := range shards {
		buffers[shard.filename] = &strings.Builder{}
	}
	for _, m := range models {
		shard := apiShardForIdentifier(m.Identifier, shards, order)
		body, hasMethod := renderGeneratedAPIModel(m)
		buffers[shard.filename].WriteString(body)
		needsContext[shard.filename] = needsContext[shard.filename] || hasMethod
	}
	for _, shard := range shards {
		var b strings.Builder
		b.WriteString("// Code generated by tools/gen; DO NOT EDIT.\npackage sdk\n\n")
		if needsContext[shard.filename] {
			b.WriteString("import \"context\"\n\n")
		}
		b.WriteString("// " + shard.comment + "\n")
		b.WriteString(buffers[shard.filename].String())
		if err := writeFormattedFile(shard.filename, []byte(b.String())); err != nil {
			return err
		}
	}
	_ = os.Remove("sdk/generated_apis.go")
	return nil
}

